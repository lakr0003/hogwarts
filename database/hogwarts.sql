-- Kør hele filen i en query-console (pgAdmin / DataGrip) på en tom database.
-- Filen kan køres igen for at nulstille data (den sletter og genopretter schemaet).

DROP SCHEMA IF EXISTS hogwarts_api CASCADE;
CREATE SCHEMA hogwarts_api;

-- ---------------------------------------------------------------
-- Tabeller
-- ---------------------------------------------------------------

CREATE TABLE hogwarts_api.houses (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            varchar(50)  NOT NULL,
    primary_color   varchar(30),
    secondary_color varchar(30),
    founder         varchar(100)
);

CREATE TABLE hogwarts_api.teachers (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     varchar(100) NOT NULL,
    house_id integer NOT NULL,
    CONSTRAINT teachers_house_fk FOREIGN KEY (house_id)
        REFERENCES hogwarts_api.houses (id) ON DELETE RESTRICT
);

CREATE TABLE hogwarts_api.students (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     varchar(100) NOT NULL,
    house_id integer NOT NULL,
    year     integer,
    CONSTRAINT students_house_fk FOREIGN KEY (house_id)
        REFERENCES hogwarts_api.houses (id) ON DELETE RESTRICT
);

CREATE TABLE hogwarts_api.courses (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(50) NOT NULL,
    teacher_id integer NOT NULL,
    CONSTRAINT course_teacher_fk FOREIGN KEY (teacher_id)
        REFERENCES hogwarts_api.teachers (id) ON DELETE RESTRICT
);

-- Koblingstabel: mange students <-> mange courses
CREATE TABLE hogwarts_api.course_students (
    course_id  integer NOT NULL,
    student_id integer NOT NULL,
    PRIMARY KEY (course_id, student_id),
    CONSTRAINT course_students_course_fk FOREIGN KEY (course_id)
        REFERENCES hogwarts_api.courses (id) ON DELETE CASCADE,
    CONSTRAINT course_students_student_fk FOREIGN KEY (student_id)
        REFERENCES hogwarts_api.students (id) ON DELETE CASCADE
);

